"""
SHIELD Security — Config Loader
=================================
Loads .shieldrc from current directory or home directory.

.shieldrc format (YAML-like, simple key=value):

  report = report.html
  k = 3
  output = shield_results
  languages = python,javascript
  exclude = tests,venv,.git
  inplace = false
  grade_fail = D

Author: Ali Yasin Idrees
Version: 1.0.5
"""

from pathlib import Path

# Default configuration
DEFAULTS = {
    "report":     None,
    "k":          3,
    "output":     "shield_results",
    "languages":  [],
    "exclude":    ["venv", ".venv", "node_modules", ".git", "__pycache__"],
    "inplace":    False,
    "grade_fail": "F",
}


def _parse_value(value: str):
    """Convert string value to appropriate Python type."""
    value = value.strip()
    if value.lower() == "true":  return True
    if value.lower() == "false": return False
    if value.lower() == "none":  return None
    if "," in value:             return [v.strip() for v in value.split(",")]
    try:                         return int(value)
    except ValueError:           return value


def load_config(start_path: str = ".") -> dict:
    """
    Load .shieldrc config file.
    Search order:
      1. Current directory
      2. Parent directories (up to 3 levels)
      3. Home directory
      4. Return defaults if none found

    Returns merged config dict.
    """
    config = DEFAULTS.copy()

    # Search locations
    search_paths = []
    current = Path(start_path).resolve()
    for _ in range(4):
        search_paths.append(current / ".shieldrc")
        current = current.parent

    search_paths.append(Path.home() / ".shieldrc")

    # Load first .shieldrc found
    for rc_path in search_paths:
        if rc_path.exists():
            try:
                for line in rc_path.read_text(encoding='utf-8').splitlines():
                    line = line.strip()
                    if not line or line.startswith('#'):
                        continue
                    if '=' in line:
                        key, _, value = line.partition('=')
                        key = key.strip()
                        if key in DEFAULTS:
                            config[key] = _parse_value(value) 
            except Exception: # nosec B110 — intentional: malformed .shieldrc lines skipped silently
                pass
            break

    return config


def create_default_config(path: str = ".shieldrc") -> str:
    """
    Create a default .shieldrc file.
    Called by: shield init
    """
    content = """# SHIELD Security Configuration
# ================================
# Generated by: shield init
# Docs: github.com/Aliidrees1234/llm-security-research

# Auto-generate HTML report on every scan
# report = shield_report.html

# Maximum FDSP fix iterations (1-3)
k = 3

# Output directory for fixed files
output = shield_results

# Exclude these folders from scanning
exclude = venv,.venv,node_modules,.git,__pycache__,tests

# Fix files in place (WARNING: modifies originals)
inplace = false

# Minimum grade before scan fails (A+, A, B, C, D, F)
grade_fail = F
"""
    Path(path).write_text(content, encoding='utf-8')
    return path